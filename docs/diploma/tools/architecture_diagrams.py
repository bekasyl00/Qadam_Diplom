def action(c,x,y,w,h,text,size=22):
    c.d.rounded_rectangle((x*2,y*2,(x+w)*2,(y+h)*2),radius=22,fill='#f4f5f7',outline='#67717e',width=3)
    c.svg.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="11" fill="#f4f5f7" stroke="#67717e" stroke-width="1.5"/>')
    lines=len(text.split('\n'))
    c.text(x+w/2,y+(h-lines*(size+7)+7)/2,text,size)

def diamond(c,x,y,w,h,label):
    pts=[(x+w/2,y),(x+w,y+h/2),(x+w/2,y+h),(x,y+h/2)]
    c.d.polygon([(a*2,b*2) for a,b in pts],fill='white',outline='#596372',width=3)
    c.svg.append('<polygon points="'+' '.join(f'{a},{b}' for a,b in pts)+'" fill="white" stroke="#596372" stroke-width="1.5"/>')
    c.text(x+w/2,y+h/2-12,label,20)

def dot(c,x,y,final=False):
    if final:
        c.d.ellipse(((x-14)*2,(y-14)*2,(x+14)*2,(y+14)*2),outline='black',width=3)
        c.svg.append(f'<circle cx="{x}" cy="{y}" r="14" fill="white" stroke="black" stroke-width="1.5"/>')
    c.d.ellipse(((x-8)*2,(y-8)*2,(x+8)*2,(y+8)*2),fill='black')
    c.svg.append(f'<circle cx="{x}" cy="{y}" r="8" fill="black"/>')

def entity(c,x,y,w,h,title,fields,dash=False):
    c.box(x,y,w,h,fill='white',dash=dash)
    c.text(x+w/2,y+13,title,24,bold=True)
    c.line([(x,y+52),(x+w,y+52)])
    for i,line in enumerate(fields):c.text(x+15,y+70+i*30,line,20,center=False)

